const MOON_LIGHT_S = 1.282; // one-way, at the mean distance of 384,400 km

// One-way Earth–Mars light time in seconds for a given date.
// ponytail: coplanar two-body orbits from JPL mean elements (J2000), good to ~1%.
// Swap for an ephemeris only if someone needs better than "about 14 minutes".
function marsLightSeconds(ms) {
  const T = (ms / 864e5 + 2440587.5 - 2451545) / 36525, rad = Math.PI / 180;
  const pos = (a, e, L0, Ld, w0, wd) => {
    const w = (w0 + wd * T) * rad, M = (L0 + Ld * T) * rad - w;
    let E = M;
    for (let i = 0; i < 8; i++) E = M + e * Math.sin(E);
    const x = a * (Math.cos(E) - e), y = a * Math.sqrt(1 - e * e) * Math.sin(E);
    return [x * Math.cos(w) - y * Math.sin(w), x * Math.sin(w) + y * Math.cos(w)];
  };
  const e = pos(1.00000261, 0.01671123, 100.46457166, 35999.37244981, 102.93768193, 0.32327364);
  const m = pos(1.52371034, 0.0933941, -4.55343205, 19140.30268499, -23.94362959, 0.44441088);
  return Math.hypot(e[0] - m[0], e[1] - m[1]) * 499.004784;
}
// Self-check: opposition of 16 Jan 2025 was ~0.64 AU, about 5.3 light-minutes.
console.assert(Math.abs(marsLightSeconds(Date.UTC(2025, 0, 16)) / 60 - 5.3) < 0.3, 'Mars light-time model is off');

